const globalForStore = globalThis as unknown as { __interlockBackend?: CampaignBackend };

function backend(): CampaignBackend {
  if (!globalForStore.__interlockBackend) {
    globalForStore.__interlockBackend = createBackend(SEEDS, signatureOf);
  }
  return globalForStore.__interlockBackend;
}

export interface StoreStatus {
  kind: "memory" | "redis";
  durable: boolean;
}

export function storeStatus(): StoreStatus {
  const b = backend();
  return { kind: b.kind, durable: b.durable };
}

export async function listCampaigns(): Promise<Campaign[]> {
  return backend().list();
}

/**
 * Find the campaign a signature belongs to.
 *
 * This scans every campaign rather than using an index, and that is a
 * considered choice rather than a shortcut. The obvious index for Hamming
 * search is LSH banding, which relies on the pigeonhole principle: split the
 * hash into more bands than the radius allows errors, and at least one band
 * must match exactly. At a radius of 12 bits out of 64 that needs 13 bands of
 * about 5 bits each, and a 5-bit band has only 32 buckets — so every lookup
 * would pull back a large fraction of the table anyway, and pay 13 round trips
 * to do it. Scanning is both simpler and faster at any size this will reach.
 *
 * A deployment with millions of campaigns would change the representation
 * first — a wider hash, which tightens the radius as a fraction of its width —
 * rather than index around a radius this loose.
 */
export async function lookup(signature: string): Promise<CampaignMatch | null> {
  return matchCampaign(signature, await backend().list());
}

export interface ReportInput {
  signature: string;
  stage: Stage;
  tier: Tier;
  family: string;
  /** SHA-256 of the browser's random device token. Never the token itself. */
  reporterHash: string;
}

export interface ReportResult {
  campaign: Campaign | null;
  isNew: boolean;
  /** True when this device has filed too many reports in the current hour. */
  throttled: boolean;
}

/**
 * Record a report against a campaign, creating one if the signature is new.
 *
 * A campaign only starts hard-blocking once enough *distinct* reporters have
 * seen it. A system where one report blocks a sender is a denial-of-service
 * weapon pointed at legitimate businesses, so the threshold and the rate limit
 * are part of the design rather than a later hardening pass.
 */
export async function report(input: ReportInput): Promise<ReportResult> {
  const b = backend();

  if (!(await b.allow(input.reporterHash))) {
    return { campaign: null, isNew: false, throttled: true };
  }

  const existing = matchCampaign(input.signature, await b.list());
  if (existing) {
    const campaign = await b.record(
      existing.campaign.id,
      input.reporterHash,
      input.stage,
      input.tier,
    );
    return { campaign, isNew: false, throttled: false };
  }

  const campaign = await b.create(
    input.signature,
    input.family,
    input.reporterHash,
    input.stage,
    input.tier,
  );
  return { campaign, isNew: true, throttled: false };
}
