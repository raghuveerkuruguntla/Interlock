/**
 * The network side of the privacy boundary.
 *
 * This is the only part of Interlock that holds anything derived from a
 * message, and what it holds is a 64-bit SimHash — not text, not a sender, not
 * a recipient, not a timestamp finer than an hour. A signature cannot be
 * inverted into the message it came from.
 *
 * It also holds a hashed device token per report, which is new and worth being
 * explicit about: distinct-reporter counting and rate limiting are the defences
 * against the report button being used as a denial-of-service weapon against a
 * legitimate business, and neither is possible without some notion of who filed
 * what. The token is random, generated by the browser, tied to no account and
 * no phone number, and only its SHA-256 is ever stored.
 */

